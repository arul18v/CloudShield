"""JSON and standalone HTML report generation."""

import html
import json
from pathlib import Path


def write_reports(findings, output_dir="reports", source="CloudShield"):
    output = Path(output_dir)
    output.mkdir(parents=True, exist_ok=True)
    json_path = output / "cloudshield-report.json"
    html_path = output / "cloudshield-report.html"

    summary = {
        "total_checks": len(findings),
        "passed": sum(item["status"] == "PASS" for item in findings),
        "failed": sum(item["status"] == "FAIL" for item in findings),
        "errors": sum(item["status"] == "ERROR" for item in findings),
    }
    payload = {"source": source, "summary": summary, "findings": findings}
    json_path.write_text(json.dumps(payload, indent=2), encoding="utf-8")

    rows = []
    for item in findings:
        values = [
            item.get("severity", ""),
            item.get("status", ""),
            item.get("check", ""),
            item.get("resource", ""),
            item.get("message", ""),
            item.get("recommendation", ""),
        ]
        cells = "".join(f"<td>{html.escape(str(value))}</td>" for value in values)
        rows.append(f"<tr>{cells}</tr>")

    document = f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>CloudShield Security Report</title>
<style>
:root {{ color-scheme: light; font-family: Inter, system-ui, sans-serif; }}
body {{ margin: 0; padding: 32px; background: #f3f6fb; color: #172033; }}
main {{ max-width: 1200px; margin: auto; }}
header, .stat, .panel {{ background: white; border: 1px solid #e2e8f0; border-radius: 14px; }}
header {{ padding: 24px; margin-bottom: 18px; }}
h1 {{ margin: 0 0 8px; }}
.muted {{ color: #64748b; }}
.stats {{ display: grid; grid-template-columns: repeat(auto-fit,minmax(140px,1fr)); gap: 12px; margin-bottom: 18px; }}
.stat {{ padding: 18px; }} .number {{ font-size: 28px; font-weight: 700; }}
.panel {{ overflow-x: auto; padding: 8px; }}
table {{ width: 100%; border-collapse: collapse; font-size: 14px; }}
th, td {{ padding: 12px; border-bottom: 1px solid #e2e8f0; text-align: left; vertical-align: top; }}
th {{ background: #f8fafc; }} tr:last-child td {{ border-bottom: 0; }}
@media(max-width:650px) {{ body {{ padding: 14px; }} }}
</style>
</head>
<body><main>
<header><h1>CloudShield</h1><div class="muted">AWS security configuration report · {html.escape(source)}</div></header>
<section class="stats">
<div class="stat"><div class="muted">Total checks</div><div class="number">{summary["total_checks"]}</div></div>
<div class="stat"><div class="muted">Passed</div><div class="number">{summary["passed"]}</div></div>
<div class="stat"><div class="muted">Failed</div><div class="number">{summary["failed"]}</div></div>
<div class="stat"><div class="muted">Errors</div><div class="number">{summary["errors"]}</div></div>
</section>
<section class="panel"><table><thead><tr><th>Severity</th><th>Status</th><th>Check</th><th>Resource</th><th>Finding</th><th>Recommendation</th></tr></thead>
<tbody>{"".join(rows)}</tbody></table></section>
<p class="muted">Generated by CloudShield. Findings are advisory; validate against your environment and security requirements.</p>
</main></body></html>"""
    html_path.write_text(document, encoding="utf-8")
    return json_path, html_path
